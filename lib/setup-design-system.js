async function createComponents(designSystemDir) {
  // Button component
  const buttonComponent = `import React from 'react';

interface ButtonProps extends React.ButtonHTMLAttributes<HTMLButtonElement> {
  variant?: 'primary' | 'secondary' | 'outline';
  size?: 'default' | 'large';
  children: React.ReactNode;
}

export function Button({
  variant = 'primary',
  size = 'default',
  children,
  className = '',
  ...props
}: ButtonProps) {
  const baseStyles = 'inline-flex items-center justify-center rounded-[var(--radius-pill)] font-medium transition-all duration-[var(--duration-fast)] disabled:opacity-50 disabled:pointer-events-none';
  
  const variantStyles = {
    primary: 'bg-[var(--color-primary)] text-[var(--color-primary-foreground)] hover:opacity-90',
    secondary: 'bg-[var(--color-secondary)] text-[var(--color-secondary-foreground)] hover:opacity-90',
    outline: 'border-2 border-[var(--color-border)] text-[var(--color-text-primary)] hover:bg-[var(--color-surface-elevated)]'
  };
  
  const sizeStyles = {
    default: 'h-[var(--size-button-default)] px-[var(--spacing-6)] text-[var(--font-size-base)]',
    large: 'h-[var(--size-button-large)] px-[var(--spacing-8)] text-[var(--font-size-lg)]'
  };
  
  return (
    <button
      className={\`\${baseStyles} \${variantStyles[variant]} \${sizeStyles[size]} \${className}\`}
      {...props}
    >
      {children}
    </button>
  );
}
`;

  // Input component
  const inputComponent = `import React from 'react';

interface InputProps extends React.InputHTMLAttributes<HTMLInputElement> {
  label?: string;
  error?: boolean;
  helperText?: string;
}

export function Input({
  label,
  error = false,
  helperText,
  className = '',
  ...props
}: InputProps) {
  return (
    <div className="flex flex-col gap-[var(--spacing-2)]">
      {label && (
        <label className="text-[var(--font-size-sm)] font-medium text-[var(--color-text-primary)]">
          {label}
        </label>
      )}
      <input
        className={\`w-full h-[var(--size-button-default)] px-[var(--spacing-4)] rounded-[var(--radius-sm)] border-2 \${
          error
            ? 'border-[var(--color-destructive)] focus:border-[var(--color-destructive)]'
            : 'border-[var(--color-input)] focus:border-[var(--color-primary)]'
        } bg-[var(--color-background)] text-[var(--color-text-primary)] outline-none transition-colors duration-[var(--duration-fast)] \${className}\`}
        {...props}
      />
      {helperText && (
        <p className={\`text-[var(--font-size-xs)] \${error ? 'text-[var(--color-destructive)]' : 'text-[var(--color-text-secondary)]'}\`}>
          {helperText}
        </p>
      )}
    </div>
  );
}
`;

  // Modal component
  const modalComponent = `'use client';

import React, { useEffect } from 'react';

interface ModalProps {
  isOpen: boolean;
  onClose: () => void;
  title?: string;
  children: React.ReactNode;
}

export function Modal({ isOpen, onClose, title, children }: ModalProps) {
  useEffect(() => {
    const handleEscape = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    
    if (isOpen) {
      document.addEventListener('keydown', handleEscape);
      document.body.style.overflow = 'hidden';
    }
    
    return () => {
      document.removeEventListener('keydown', handleEscape);
      document.body.style.overflow = 'unset';
    };
  }, [isOpen, onClose]);
  
  if (!isOpen) return null;
  
  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-[var(--spacing-4)]">
      <div className="absolute inset-0 bg-black/50" onClick={onClose} />
      <div className="relative bg-[var(--color-surface-base)] rounded-[var(--radius-m)] p-[var(--spacing-6)] max-w-md w-full shadow-[var(--shadow-xl)]">
        {title && <h2 className="text-[var(--font-size-xl)] font-bold text-[var(--color-text-primary)] mb-[var(--spacing-4)]">{title}</h2>}
        {children}
      </div>
    </div>
  );
}
`;

  // EmptyState component
  const emptyStateComponent = `import React from 'react';

interface EmptyStateProps {
  icon?: string;
  title: string;
  description?: string;
  action?: {
    label: string;
    onClick: () => void;
  };
}

export function EmptyState({ icon, title, description, action }: EmptyStateProps) {
  return (
    <div className="flex flex-col items-center justify-center p-[var(--spacing-12)] text-center">
      {icon && <div className="text-6xl mb-[var(--spacing-4)]">{icon}</div>}
      <h3 className="text-[var(--font-size-lg)] font-semibold text-[var(--color-text-primary)] mb-[var(--spacing-2)]">
        {title}
      </h3>
      {description && (
        <p className="text-[var(--font-size-base)] text-[var(--color-text-secondary)] mb-[var(--spacing-6)] max-w-md">
          {description}
        </p>
      )}
      {action && (
        <button
          onClick={action.onClick}
          className="px-[var(--spacing-6)] h-[var(--size-button-default)] rounded-[var(--radius-pill)] bg-[var(--color-primary)] text-[var(--color-primary-foreground)] hover:opacity-90 transition-opacity"
        >
          {action.label}
        </button>
      )}
    </div>
  );
}
`;

  // Placeholder component
  const placeholderComponent = `import React from 'react';

interface PlaceholderProps {
  aspect?: 'square' | 'video' | 'portrait' | 'landscape';
  label?: string;
}

export function Placeholder({ aspect = 'square', label }: PlaceholderProps) {
  const aspectRatios = {
    square: 'aspect-square',
    video: 'aspect-video',
    portrait: 'aspect-[3/4]',
    landscape: 'aspect-[4/3]'
  };
  
  return (
    <div className={\`\${aspectRatios[aspect]} w-full bg-[var(--color-surface-elevated)] rounded-[var(--radius-m)] flex items-center justify-center border-2 border-dashed border-[var(--color-border)]\`}>
      {label && (
        <span className="text-[var(--font-size-sm)] text-[var(--color-text-muted)]">{label}</span>
      )}
    </div>
  );
}
`;

  // Index file
  const indexFile = `export { Button } from './Button';
export { Input } from './Input';
export { Modal } from './Modal';
export { EmptyState } from './EmptyState';
export { Placeholder } from './Placeholder';
`;

  // Write all component files
  await fs.writeFile(path.join(designSystemDir, 'Button.tsx'), buttonComponent);
  await fs.writeFile(path.join(designSystemDir, 'Input.tsx'), inputComponent);
  await fs.writeFile(path.join(designSystemDir, 'Modal.tsx'), modalComponent);
  await fs.writeFile(path.join(designSystemDir, 'EmptyState.tsx'), emptyStateComponent);
  await fs.writeFile(path.join(designSystemDir, 'Placeholder.tsx'), placeholderComponent);
  await fs.writeFile(path.join(designSystemDir, 'index.tsx'), indexFile);
}

