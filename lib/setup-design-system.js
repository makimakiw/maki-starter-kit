import fs from 'fs-extra';
import path from 'path';
import chalk from 'chalk';
import ora from 'ora';

export async function setupDesignSystem(projectDir, projectInfo) {
  const spinner = ora('Setting up design system...').start();

  try {
    const { primaryColor, darkMode, categoryColors } = projectInfo;

    // 1. Create globals.css with design tokens
    await createGlobalsCss(projectDir, { primaryColor, darkMode });
    
    // 2. Create design-system folder
    const designSystemDir = path.join(projectDir, 'design-system', 'pencildraw');
    await fs.ensureDir(designSystemDir);
    
    // 3. Create core components
    await createComponents(designSystemDir);
    
    // 4. Update homepage to showcase components
    await updateHomepage(projectDir);
    
    // 5. Create documentation
    await createDocumentation(projectDir, { primaryColor, darkMode, categoryColors });

    spinner.succeed(chalk.green('Design system set up successfully!'));

    // Show what was created
    console.log(chalk.dim('\n  Design system includes:'));
    console.log(chalk.dim('    • 62 design tokens (colors, spacing, typography)'));
    console.log(chalk.dim('    • 5 core components (Button, Input, Modal, EmptyState, Placeholder)'));
    console.log(chalk.dim('    • Component showcase on homepage'));
    console.log(chalk.dim('    • Documentation and best practices'));

    return true;

  } catch (error) {
    spinner.fail(chalk.red('Failed to set up design system'));
    throw error;
  }
}

